import { createTreeWithEmptyWorkspace } from '@nx/devkit/testing';
import type { Tree } from '@nx/devkit';

/** Nx's React app config shape, which add-fsd-lite writes the rule into. */
export const APP_ESLINT_CONFIG = "import baseConfig from '../eslint.config.mjs';\n\nexport default [\n  ...baseConfig,\n];\n";

export interface Layout {
  name: string;
  frontend: 'react-vite' | 'next' | 'expo';
  build(): Tree;
  /** The app's directory, where its eslint.config.mjs lives. */
  appRoot: string;
  /** Where the layers must land. */
  sourceRoot: string;
  /** `root` as the app's config must name it. */
  eslintRoot: string;
}

function app(tree: Tree, root: string, config: Record<string, unknown>): void {
  const prefix = root === '.' ? '' : `${root}/`;
  tree.write(`${prefix}project.json`, JSON.stringify({ projectType: 'application', ...config }));
  tree.write(`${prefix}eslint.config.mjs`, APP_ESLINT_CONFIG);
  tree.write(`${prefix}jest.config.ts`, 'export default {};\n');
}

